def replace(i, old, new):
    p = P[i]
    runs = p.runs
    texts = [r.text for r in runs]
    full = "".join(texts)
    idx = full.find(old)
    if idx < 0:
        errors.append(f"[{i}] not found: {old[:60]}")
        return
    end = idx + len(old)
    pos = 0
    si = sj = None
    for k, t in enumerate(texts):
        if si is None and idx < pos + len(t):
            si, so = k, idx - pos
        if si is not None and end <= pos + len(t):
            sj, eo = k, end - pos
            break
        pos += len(t)
    if si == sj:
        runs[si].text = texts[si][:so] + new + texts[si][eo:]
    else:
        runs[si].text = texts[si][:so] + new
        for k in range(si + 1, sj):
            runs[k].text = ""
        runs[sj].text = texts[sj][eo:]
    log.append({"paragraph": i, "old": old, "new": new})


def set_text(p, text):
    runs = [r for r in p.runs if r.text or not r._r.xpath(".//w:drawing")]
    runs[0].text = text
    for r in runs[1:]:
        r._r.getparent().remove(r._r)


def highlight(p):
    for r in p.runs:
        rpr = r._r.get_or_add_rPr()
        h = OxmlElement("w:highlight")
        h.set(qn("w:val"), "yellow")
        rpr.append(h)


def insert_after(p, text, mark=False):
    new = copy.deepcopy(p._p)
    p._p.addnext(new)
    np = docx.text.paragraph.Paragraph(new, p._parent)
    set_text(np, text)
    if mark:
        highlight(np)
    log.append({"inserted_after": p.text[:50], "text": text, "highlighted": mark})
    return np


def delete(p):
    p._p.getparent().remove(p._p)


