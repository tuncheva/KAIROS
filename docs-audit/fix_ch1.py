def fix_ai(text):
    text = re.sub(r"(?<=[A-Za-z])ИИ(?=[a-z])", "ai", text)
    text = re.sub(r"ИИ(?=[a-z])", "Ai", text)
    return re.sub(r"(?<=[A-Za-z])ИИ", "AI", text)

